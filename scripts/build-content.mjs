#!/usr/bin/env node
/**
 * Bundles the editable content in `content/` into the static JSON that the app
 * imports.
 *
 * Why a build step rather than reading `content/` directly: `lib/projects.ts`
 * is imported by `components/GalleryGrid.tsx`, which is a client component, so
 * the project list is bundled for the browser and cannot come from `fs` at
 * runtime. A folder of one-file-per-project is what makes the CMS pleasant to
 * use — each project is its own entry with its own editor — so the folder is
 * the source of truth and this collapses it into one import the bundler can
 * follow.
 *
 * Runs automatically before `dev`, `build` and `typecheck` (npm `pre*` hooks),
 * so a CMS commit that only touches `content/` is picked up by the next deploy
 * with nothing to remember. The generated files are committed too, so a fresh
 * clone type-checks before anything has been run.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const GENERATED_HEADER = "// Generated by scripts/build-content.mjs — do not edit by hand.";

/** Sorted by `order` so the gallery and `populatedSectors` keep a stable sequence. */
async function bundleProjects() {
  const dir = "content/projects";
  const files = (await readdir(dir)).filter((f) => f.endsWith(".json")).sort();

  const projects = [];
  for (const file of files) {
    const raw = await readFile(path.join(dir, file), "utf8");
    let record;
    try {
      record = JSON.parse(raw);
    } catch (error) {
      throw new Error(`${dir}/${file} is not valid JSON: ${error.message}`);
    }

    // The filename is the slug. Trusting the field instead would let a rename
    // in the CMS silently point a project at another project's photograph.
    const slug = path.basename(file, ".json");
    if (record.slug && record.slug !== slug) {
      throw new Error(
        `${dir}/${file}: slug "${record.slug}" does not match its filename. ` +
          `The filename is authoritative — rename the file instead.`,
      );
    }
    if (!record.title || !record.sector) {
      throw new Error(`${dir}/${file}: every project needs a title and a sector.`);
    }

    const { order, ...rest } = record;
    projects.push({ order: typeof order === "number" ? order : 9999, ...rest, slug });
  }

  projects.sort((a, b) => a.order - b.order || a.slug.localeCompare(b.slug));

  // `order` has done its job once the array is sorted; it is not part of the
  // Project shape the app consumes.
  const out = projects.map((project) => {
    const copy = { ...project };
    delete copy.order;
    return copy;
  });
  await writeFile("content/projects.generated.json", JSON.stringify(out, null, 2) + "\n");
  return out.length;
}

async function main() {
  const count = await bundleProjects();
  console.log(`${GENERATED_HEADER}\n✓ content/projects.generated.json — ${count} projects`);
}

main().catch((error) => {
  console.error(`\nContent build failed:\n  ${error.message}\n`);
  process.exit(1);
});
